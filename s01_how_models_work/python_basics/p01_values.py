# A variable is a labelled box that holds a value
name = "Maya"        # text, called a string
order_id = 1042      # a whole number, called an integer
price = 24.99        # a number with a decimal point, called a float
paid = True          # True or False, called a boolean

print(name, order_id, price, paid)
print(f"Hi {name}, order {order_id} costs ${price}.")
